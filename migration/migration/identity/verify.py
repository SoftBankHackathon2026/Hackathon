"""Configuration verification and separately labeled real-identity authorization probes."""

from __future__ import annotations

from .adapters import Http
from .common import IdentityError, keys, require, secret, string
from .plan import validate_plan


def validate_checks(checks, config, plan):
    keys(checks, {"schema_version", "checks"}, {"schema_version", "checks"})
    require(
        type(checks["schema_version"]) is int and checks["schema_version"] == 1,
        "CHECK_SCHEMA_VERSION",
    )
    require(isinstance(checks["checks"], list), "CHECK_LIST_REQUIRED")
    groups = {row["target_group"] for row in plan["mapping_rows"]}
    for c in checks["checks"]:
        keys(
            c,
            {
                "kind",
                "group",
                "token_env",
                "expected_subject",
                "allowed",
                "namespace",
                "verb",
                "resource",
                "api_group",
                "path",
                "role",
                "resource_name",
            },
            {"kind", "group", "token_env", "expected_subject", "allowed"},
        )
        require(
            c["kind"] in {"kubernetes", "openbao"} and c["kind"] in config["targets"],
            "CHECK_TARGET",
        )
        require(
            c["group"] in groups and type(c["allowed"]) is bool,
            "CHECK_GROUP_OR_EXPECTATION",
        )
        string(c["token_env"])
        string(c["expected_subject"])
        if c["kind"] == "kubernetes":
            require(
                all(k in c for k in ("namespace", "verb", "resource", "api_group")),
                "KUBERNETES_CHECK_FIELDS",
            )
            require(
                c["verb"]
                in {"get", "list", "watch", "create", "update", "patch", "delete"},
                "CHECK_VERB",
            )
            for f in ("namespace", "resource"):
                string(c[f])
            require(isinstance(c["api_group"], str), "CHECK_API_GROUP")
        else:
            require("path" in c and "role" in c, "OPENBAO_CHECK_FIELDS")
            require(
                c["path"].count("/") >= 2
                and ".." not in c["path"].split("/")
                and not any(x in c["path"] for x in "?#\\")
                and not c["path"].startswith("/"),
                "CHECK_PATH",
            )
            # Only roles generated by this plan can be used to obtain test tokens.
            require(
                any(
                    r["kind"] == "bao_role"
                    and r["name"].split("/", 1)[1] == c["role"]
                    and r["payload"]["bound_claims"]["groups"] == c["group"]
                    for r in plan["resources"]
                ),
                "CHECK_ROLE",
            )
    return checks


def kubernetes_probe(c, config):
    from .adapters import KubernetesHttp

    k = config["targets"]["kubernetes"]
    api = KubernetesHttp(k, user_token=secret(c["token_env"]))
    review = api.request(
        "POST",
        "/apis/authentication.k8s.io/v1/selfsubjectreviews",
        payload={"apiVersion": "authentication.k8s.io/v1", "kind": "SelfSubjectReview"},
    )
    user = review["status"]["userInfo"]
    require(
        user["username"] == "keycloak:" + c["expected_subject"],
        "PROBE_SUBJECT_MISMATCH",
    )
    require(
        k["group_prefix"] + c["group"] in user.get("groups", []), "PROBE_GROUP_MISMATCH"
    )
    attrs = {
        "namespace": c["namespace"],
        "verb": c["verb"],
        "resource": c["resource"],
        "group": c["api_group"],
    }
    if "resource_name" in c:
        attrs["name"] = c["resource_name"]
    access = api.request(
        "POST",
        "/apis/authorization.k8s.io/v1/selfsubjectaccessreviews",
        payload={
            "apiVersion": "authorization.k8s.io/v1",
            "kind": "SelfSubjectAccessReview",
            "spec": {"resourceAttributes": attrs},
        },
    )
    require(not access["status"].get("evaluationError"), "KUBERNETES_EVALUATION_ERROR")
    require(
        access["status"].get("allowed") is c["allowed"],
        "UNEXPECTED_AUTHORIZATION_DECISION",
    )
    return "authenticated_self_subject_access_review"


def openbao_probe(c, config):
    from .adapters import segment

    b = config["targets"]["openbao"]
    unauthenticated = Http(
        b["base_url"], ca_file=b.get("ca_file"), header="X-Vault-Token", token_value=""
    )
    login = unauthenticated.request(
        "POST",
        "/v1/auth/" + segment(b["auth_mount"]) + "/login",
        payload={"role": c["role"], "jwt": secret(c["token_env"])},
    )
    token = login["auth"]["client_token"]
    http = Http(
        b["base_url"],
        ca_file=b.get("ca_file"),
        header="X-Vault-Token",
        token_value=token,
    )
    try:
        require(
            login["auth"].get("metadata", {}).get("source_subject")
            == c["expected_subject"],
            "PROBE_SUBJECT_MISMATCH",
        )
        try:
            # A real read is used; no secret response is added to artifacts or stdout.
            http.request(
                "GET", "/v1/" + "/".join(segment(part) for part in c["path"].split("/"))
            )
            allowed = True
        except IdentityError as error:
            if error.code != "TARGET_HTTP_403":
                raise
            allowed = False
        require(allowed == c["allowed"], "UNEXPECTED_AUTHORIZATION_DECISION")
    finally:
        http.request("POST", "/v1/auth/token/revoke-self")
    return "authenticated_secret_read"


def verify(config, plan, targets, checks=None, probes=None):
    validate_plan(plan, config)
    result = {
        "schema_version": 1,
        "operation": "verify",
        "plan_hash": plan["plan_hash"],
        "configuration": [],
        "access": [],
        "handoffs": plan["handoffs"],
        "migration_status": "partial_pending_onboarding_and_external_handoffs",
    }
    for r in plan["resources"]:
        try:
            state = "pass" if targets.read(r) == r["payload"] else "fail"
            result["configuration"].append({"id": r["id"], "status": state})
        except IdentityError as error:
            result["configuration"].append(
                {"id": r["id"], "status": "unknown", "reason": error.code}
            )
    if checks is not None:
        validate_checks(checks, config, plan)
    probes = probes or {"kubernetes": kubernetes_probe, "openbao": openbao_probe}
    for index, c in enumerate((checks or {}).get("checks", [])):
        item = {
            "index": index,
            "kind": c["kind"],
            "group": c["group"],
            "expected_allowed": c["allowed"],
        }
        try:
            item.update(status="pass", method=probes[c["kind"]](c, config))
        except IdentityError as error:
            item.update(status="fail", reason=error.code)
        except Exception:  # noqa: BLE001 -- probes must never serialize token-bearing SDK errors.
            item.update(status="unknown", reason="ACCESS_PROBE_FAILED")
        result["access"].append(item)
    covered = {
        (x["kind"], x["group"], x["expected_allowed"])
        for x in result["access"]
        if x["status"] == "pass"
    }
    required = {
        (kind, row["target_group"], allowed)
        for row in plan["mapping_rows"]
        for kind in ("kubernetes", "openbao")
        if kind in row["targets"]
        for allowed in (True, False)
    }
    result["missing_access_coverage"] = [
        {"kind": k, "group": g, "allowed": a} for k, g, a in sorted(required - covered)
    ]
    failed = any(
        x["status"] != "pass" for x in result["configuration"] + result["access"]
    )
    result["configuration_status"] = (
        "failed"
        if any(x["status"] != "pass" for x in result["configuration"])
        else "complete"
    )
    result["access_status"] = (
        "not_run"
        if not result["access"]
        else "failed"
        if failed
        else "partial"
        if required - covered
        else "complete"
    )
    # This command cannot certify onboarding or application/control-plane deployment.
    # Completing configuration or a subset of probes never means the migration is complete.
    result["status"] = "failed" if failed else "partial"
    return result
